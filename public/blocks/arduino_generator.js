const arduinoGenerator = new Blockly.Generator('Arduino');

// ── Operator Precedence ─────────────────────────────────────
arduinoGenerator.ORDER_ATOMIC = 0;
arduinoGenerator.ORDER_UNARY = 1;
arduinoGenerator.ORDER_MULTIPLICATIVE = 2;
arduinoGenerator.ORDER_ADDITIVE = 3;
arduinoGenerator.ORDER_RELATIONAL = 4;
arduinoGenerator.ORDER_EQUALITY = 5;
arduinoGenerator.ORDER_LOGICAL_AND = 6;
arduinoGenerator.ORDER_LOGICAL_OR = 7;
arduinoGenerator.ORDER_ASSIGNMENT = 8;
arduinoGenerator.ORDER_NONE = 99;

// ── Internal storage ────────────────────────────────────────
arduinoGenerator.includes_ = {};
arduinoGenerator.declarations_ = {};
arduinoGenerator.setups_ = {};

arduinoGenerator.init = function(workspace) {
  this.includes_ = {};
  this.declarations_ = {};
  this.setups_ = {};
  
  if (!this.nameDB_) {
    this.nameDB_ = new Blockly.Names(this.RESERVED_WORDS_);
  } else {
    this.nameDB_.reset();
  }
};

arduinoGenerator.finish = function(code) {
  var includes = Object.values(this.includes_).join('\n');
  var declarations = Object.values(this.declarations_).join('\n');
  var setups = Object.values(this.setups_).join('\n  ');

  var output = '';
  output += '// ================================\n';
  output += '// Generated by ArduiBlok\n';
  output += '// ================================\n\n';

  if (includes) {
    output += includes + '\n\n';
  }

  if (declarations) {
    output += declarations + '\n\n';
  }

  output += 'void setup() {\n';
  if (setups) {
    output += '  ' + setups + '\n';
  }
  output += '}\n\n';

  output += 'void loop() {\n';
  output += code || '';
  output += '}\n';

  return output;
};

arduinoGenerator.scrub_ = function(block, code, thisOnly) {
  var nextBlock = block.nextConnection && block.nextConnection.targetBlock();
  if (nextBlock && !thisOnly) {
    return code + this.blockToCode(nextBlock);
  }
  return code;
};

// ── BLOCK GENERATORS ────────────────────────────────────────

arduinoGenerator.forBlock['arduino_setup'] = function(block, generator) {
  var setupCode = generator.statementToCode(block, 'SETUP_CODE');
  if (setupCode.trim()) {
    generator.setups_['user_setup'] = setupCode.trim();
  }
  return '';
};

arduinoGenerator.forBlock['arduino_loop'] = function(block, generator) {
  var loopCode = generator.statementToCode(block, 'LOOP_CODE');
  return loopCode;
};

arduinoGenerator.forBlock['motor_dc'] = function(block, generator) {
  var pinIn1 = block.getFieldValue('PIN_IN1');
  var pinIn2 = block.getFieldValue('PIN_IN2');
  var pinEna = block.getFieldValue('PIN_ENA');
  var direction = block.getFieldValue('DIRECTION');
  var speed = block.getFieldValue('SPEED');

  generator.setups_['pin_' + pinIn1] = 'pinMode(' + pinIn1 + ', OUTPUT);';
  generator.setups_['pin_' + pinIn2] = 'pinMode(' + pinIn2 + ', OUTPUT);';
  generator.setups_['pin_' + pinEna] = 'pinMode(' + pinEna + ', OUTPUT);';

  var code = '';
  if (direction === 'FORWARD') {
    code += '  digitalWrite(' + pinIn1 + ', HIGH);\n';
    code += '  digitalWrite(' + pinIn2 + ', LOW);\n';
    code += '  analogWrite(' + pinEna + ', ' + speed + ');\n';
  } else if (direction === 'BACKWARD') {
    code += '  digitalWrite(' + pinIn1 + ', LOW);\n';
    code += '  digitalWrite(' + pinIn2 + ', HIGH);\n';
    code += '  analogWrite(' + pinEna + ', ' + speed + ');\n';
  } else {
    code += '  digitalWrite(' + pinIn1 + ', LOW);\n';
    code += '  digitalWrite(' + pinIn2 + ', LOW);\n';
    code += '  analogWrite(' + pinEna + ', 0);\n';
  }

  return code;
};

arduinoGenerator.forBlock['digital_write'] = function(block, generator) {
  var pin = block.getFieldValue('PIN');
  var value = block.getFieldValue('VALUE');
  generator.setups_['pin_' + pin] = 'pinMode(' + pin + ', OUTPUT);';
  return '  digitalWrite(' + pin + ', ' + value + ');\n';
};

