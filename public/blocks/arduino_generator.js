arduinoGenerator.forBlock['servo_write'] = function(block, generator) {
  var pin = block.getFieldValue('PIN');
  var angle = block.getFieldValue('ANGLE');

  generator.includes_['servo'] = '#include <Servo.h>';
  generator.declarations_['servo_' + pin] = 'Servo servo_pin' + pin + ';';
  generator.setups_['servo_attach_' + pin] = 'servo_pin' + pin + '.attach(' + pin + ');';

  return '  servo_pin' + pin + '.write(' + angle + ');\n';
};

